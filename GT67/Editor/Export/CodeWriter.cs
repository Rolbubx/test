using System.Globalization;
using System.Text;
using GT67.Core;
using OpenTK.Mathematics;

namespace GT67.Editor.Export;

/// <summary>Builds the text of one generated C# file: indentation, header, usings and the literal formatting every exporter shares.</summary>
public sealed class CodeWriter
{
    private readonly StringBuilder _sb = new();
    private int _indent;

    /// <summary>A bare writer without banner (for pieces that are pasted into another file with <see cref="Raw"/>).</summary>
    public CodeWriter() { }

    /// <summary>Appends text that is already indented and complete.</summary>
    public void Raw(string text) => _sb.AppendLine(text.TrimEnd('\r', '\n'));

    /// <summary>Starts a file: auto-generated banner, usings and the namespace (GT67.Generated, or a scene's own one).</summary>
    public CodeWriter(string description, string ns = ExportContext.RootNamespace)
    {
        _sb.AppendLine("// <auto-generated>");
        _sb.AppendLine("// " + description);
        _sb.AppendLine("// Written by the GT67 editor (Compile button) on " + DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture) + ".");
        _sb.AppendLine("// Do not edit by hand: the whole Generated/GeneratedGame folder is rewritten every time you press Compile.");
        _sb.AppendLine("// </auto-generated>");
        _sb.AppendLine("#nullable enable");
        _sb.AppendLine("using System.Runtime.InteropServices;");
        _sb.AppendLine("using GT67.Core;");
        _sb.AppendLine("using GT67.UI;");
        _sb.AppendLine("using GT67.Utils;");
        _sb.AppendLine("using OpenTK.Mathematics;");
        _sb.AppendLine();
        _sb.AppendLine($"namespace {ns};");
        _sb.AppendLine();
    }

    public int Indent
    {
        get => _indent;
        set => _indent = value;
    }

    public void Line(string text = "")
    {
        if (text.Length == 0) _sb.AppendLine();
        else _sb.Append(' ', _indent * 4).AppendLine(text);
    }

    /// <summary>Writes <paramref name="header"/>, then "{" and indents; <see cref="Close"/> undoes it.</summary>
    public void Open(string header)
    {
        Line(header);
        Line("{");
        _indent++;
    }

    public void Close(string suffix = "")
    {
        _indent--;
        Line("}" + suffix);
    }

    public override string ToString() => _sb.ToString();

    // ---- initializers ----------------------------------------------------------------------------

    /// <summary>
    /// Writes <c>{ Name = value, ... }</c> for every supported setting of <paramref name="obj"/> that differs from
    /// <paramref name="defaults"/> (all of them when null), after the <paramref name="extra"/> assignments.
    /// </summary>
    public void Initializer(object obj, object? defaults, string[]? exclude = null, string[]? extra = null, string closing = ";")
    {
        var lines = new List<string>();
        if (extra != null) lines.AddRange(extra);
        foreach (var parameter in ParameterAccess.Describe(obj))
        {
            if (exclude != null && exclude.Contains(parameter.Name)) continue;
            if (defaults != null && Equals(parameter.Value, ParameterAccess.Get(defaults, parameter.Name))) continue;
            lines.Add($"{parameter.Name} = {Literal(parameter.Value!)}");
        }

        Line("{");
        _indent++;
        foreach (var line in lines) Line(line + ",");
        _indent--;
        Line("}" + closing);
    }

    // ---- literals --------------------------------------------------------------------------------

    public static string F(float value)
    {
        if (float.IsNaN(value) || float.IsInfinity(value)) return "0f";
        return value.ToString("R", CultureInfo.InvariantCulture) + "f";
    }

    public static string Bool(bool value) => value ? "true" : "false";
    public static string V3(Vector3 v) => $"new Vector3({F(v.X)}, {F(v.Y)}, {F(v.Z)})";
    public static string Col(Color4 c) => $"new Color4({F(c.R)}, {F(c.G)}, {F(c.B)}, {F(c.A)})";

    public static string Str(string s) =>
        "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r").Replace("\t", "\\t") + "\"";

    public static string Literal(object value) => value switch
    {
        float f => F(f),
        int i => i.ToString(CultureInfo.InvariantCulture),
        bool b => Bool(b),
        string s => Str(s),
        Vector2 v => $"new Vector2({F(v.X)}, {F(v.Y)})",
        Vector3 v => V3(v),
        Vector4 v => $"new Vector4({F(v.X)}, {F(v.Y)}, {F(v.Z)}, {F(v.W)})",
        Color4 c => Col(c),
        Enum e => $"global::{e.GetType().FullName!.Replace('+', '.')}.{e}",
        _ => throw new NotSupportedException($"Cannot write a {value.GetType().Name} as code."),
    };

    /// <summary>A C# identifier fragment made from an object name ("Tree 2" becomes "Tree2").</summary>
    public static string Identifier(string name)
    {
        var sb = new StringBuilder();
        foreach (char c in name)
            if (char.IsLetterOrDigit(c) || c == '_') sb.Append(c);
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }
}
